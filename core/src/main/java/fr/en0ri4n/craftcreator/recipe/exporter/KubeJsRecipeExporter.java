package fr.en0ri4n.craftcreator.recipe.exporter;

import com.google.gson.JsonObject;
import fr.en0ri4n.craftcreator.CraftCreatorAPI;
import fr.en0ri4n.craftcreator.api.CCReferences;
import fr.en0ri4n.craftcreator.api.mod.SupportedMod;
import fr.en0ri4n.craftcreator.api.mod.SupportedRecipeExporter;
import fr.en0ri4n.craftcreator.recipe.serialize.RecipeSerializer;
import fr.en0ri4n.craftcreator.recipe.utils.RecipeRequestFeedback;
import fr.en0ri4n.craftcreator.serialize.GsonProvider;
import fr.en0ri4n.craftcreator.utils.Feedback;
import fr.en0ri4n.craftcreator.utils.Identifier;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes added and removed recipes into kubejs/server_scripts/craftcreator_recipes.js, one line per entry
 * inside a single recipes event:
 * <pre>
 * onEvent('recipes', event => {
 *   event.custom({"type":"minecraft:smelting",...}).id('craftcreator:iron_ingot_from_smelting_1a2b3')
 *   event.remove({"id":"minecraft:stick"})
 *   event.replaceInput({"input":"minecraft:stick"}, 'minecraft:stick', Ingredient.of('#minecraft:saplings'))
 * })
 * </pre>
 * Deleting a line removes the entry. Other lines written in the event are kept as they are.
 * Changes are applied by KubeJS on the next /reload.
 */
public class KubeJsRecipeExporter extends AdvancedModRecipeExporter
{
    private static final String SCRIPT_NAME = "craftcreator_recipes.js";
    private static final String HEADER = """
            // Generated by Craft Creator: one line per recipe.
            // Delete a line to cancel it, then run /reload.
            """;
    private static final String EVENT_START = "onEvent('recipes', event => {";
    private static final String EVENT_END = "})";
    private static final String INDENT = "  ";
    private static final String CUSTOM_PREFIX = "event.custom(";
    private static final String ID_PREFIX = ").id('" + CCReferences.MOD_ID + ":";
    private static final String REMOVE_PREFIX = "event.remove(";
    /** event.replaceInput(filter, 'from', Ingredient.of('to')) or event.replaceOutput(filter, 'from', Item.of('to')) */
    private static final Pattern REPLACE_PATTERN = Pattern.compile("^event\\.replace(Input|Output)\\((\\{.*})\\s*,\\s*'([^']+)'\\s*,\\s*(?:Ingredient|Item)\\.of\\('([^']+)'\\)\\)$");

    @Override
    public void loadInternal()
    {
        if(!SupportedMod.isKubeJSLoaded())
            CraftCreatorAPI.LOGGER.warn("KubeJS not detected, KubeJS recipes won't be applied");
    }

    private Path getScriptFile()
    {
        return CraftCreatorAPI.get().getPlatform().getPaths().getGameDirectory().resolve("kubejs").resolve("server_scripts").resolve(SCRIPT_NAME);
    }

    /* ---------------- added recipes ---------------- */

    @Override
    public RecipeRequestFeedback addRecipe(JsonObject recipeJson)
    {
        if(!recipeJson.has("type") || !recipeJson.has("id") || !recipeJson.has("name"))
            return RecipeRequestFeedback.of(Feedback.INVALID_JSON_RECIPE, false);

        if(doesRecipeExist(recipeJson.get("id").getAsString()))
            return RecipeRequestFeedback.of(Feedback.ALREADY_EXISTS, false);

        List<Line> lines = readLines();
        lines.add(Line.added(recipeJson));
        if(!writeLines(lines)) return RecipeRequestFeedback.of(Feedback.KUBEJS_FILE_ERROR, false);

        return RecipeRequestFeedback.of(Feedback.KUBEJS_ADDED, true, SupportedRecipeExporter.KUBE_JS, recipeJson.get("name").getAsString(),
                                        GsonProvider.prettyGson().toJson(withoutIdAndName(recipeJson)), getScriptFile().toString());
    }

    @Override
    public RecipeRequestFeedback removeAddedRecipe(Identifier id)
    {
        List<Line> lines = readLines();
        boolean removed = lines.removeIf(line -> line.kind() == Kind.ADDED && line.json().get("id").getAsString().equals(id.getPath()));

        if(!removed) return RecipeRequestFeedback.of(Feedback.DO_NOT_EXISTS, false);
        if(!writeLines(lines)) return RecipeRequestFeedback.of(Feedback.KUBEJS_FILE_ERROR, false);
        return RecipeRequestFeedback.of(Feedback.KUBEJS_UPDATED, true);
    }

    @Override
    public List<JsonObject> getAddedRecipesJson()
    {
        return readLines().stream().filter(line -> line.kind() == Kind.ADDED).map(Line::json).toList();
    }

    /* ---------------- removals ---------------- */

    @Override
    public RecipeRequestFeedback removeRecipes(JsonObject filter)
    {
        if(filter.size() == 0) return RecipeRequestFeedback.of(Feedback.INVALID_JSON_RECIPE, false);

        List<Line> lines = readLines();
        if(lines.stream().anyMatch(line -> line.kind() == Kind.REMOVED && line.json().equals(filter)))
            return RecipeRequestFeedback.of(Feedback.ALREADY_REMOVED, false);

        lines.add(Line.removed(filter));
        if(!writeLines(lines)) return RecipeRequestFeedback.of(Feedback.KUBEJS_FILE_ERROR, false);
        return RecipeRequestFeedback.of(Feedback.KUBEJS_UPDATED, true);
    }

    @Override
    public List<JsonObject> getRemovals()
    {
        return readLines().stream().filter(line -> line.kind() == Kind.REMOVED).map(Line::json).toList();
    }

    @Override
    public RecipeRequestFeedback restoreRemoval(JsonObject filter)
    {
        List<Line> lines = readLines();
        if(!lines.removeIf(line -> line.kind() == Kind.REMOVED && line.json().equals(filter)))
            return RecipeRequestFeedback.of(Feedback.DO_NOT_EXISTS, false);

        if(!writeLines(lines)) return RecipeRequestFeedback.of(Feedback.KUBEJS_FILE_ERROR, false);
        return RecipeRequestFeedback.of(Feedback.KUBEJS_UPDATED, true);
    }

    /* ---------------- replacements ---------------- */

    @Override
    public RecipeRequestFeedback addReplacement(JsonObject replacement)
    {
        if(!isValidReplacement(replacement)) return RecipeRequestFeedback.of(Feedback.INVALID_JSON_RECIPE, false);

        List<Line> lines = readLines();
        if(lines.stream().anyMatch(line -> line.kind() == Kind.REPLACED && line.json().equals(replacement)))
            return RecipeRequestFeedback.of(Feedback.ALREADY_EXISTS, false);

        lines.add(new Line(Kind.REPLACED, replacement, null));
        if(!writeLines(lines)) return RecipeRequestFeedback.of(Feedback.KUBEJS_FILE_ERROR, false);
        return RecipeRequestFeedback.of(Feedback.KUBEJS_UPDATED, true);
    }

    private static boolean isValidReplacement(JsonObject replacement)
    {
        if(!replacement.has("kind") || !replacement.has("filter") || !replacement.has("from") || !replacement.has("to")) return false;

        String kind = replacement.get("kind").getAsString();
        String to = replacement.get("to").getAsString();
        // An output must be an item, and quotes would break the script line
        return (kind.equals("input") || kind.equals("output") && !to.startsWith("#"))
                && replacement.get("filter").isJsonObject() && replacement.getAsJsonObject("filter").size() > 0
                && !replacement.get("from").getAsString().contains("'") && !to.contains("'");
    }

    @Override
    public List<JsonObject> getReplacements()
    {
        return readLines().stream().filter(line -> line.kind() == Kind.REPLACED).map(Line::json).toList();
    }

    @Override
    public RecipeRequestFeedback cancelReplacement(JsonObject replacement)
    {
        List<Line> lines = readLines();
        if(!lines.removeIf(line -> line.kind() == Kind.REPLACED && line.json().equals(replacement)))
            return RecipeRequestFeedback.of(Feedback.DO_NOT_EXISTS, false);

        if(!writeLines(lines)) return RecipeRequestFeedback.of(Feedback.KUBEJS_FILE_ERROR, false);
        return RecipeRequestFeedback.of(Feedback.KUBEJS_UPDATED, true);
    }

    /* ---------------- script file ---------------- */

    private enum Kind
    {
        /** event.custom line; json is the recipe with Craft Creator's "id" and "name" */
        ADDED,
        /** event.remove line; json is the filter */
        REMOVED,
        /** event.replaceInput or event.replaceOutput line; json is the replacement */
        REPLACED,
        /** Any other line of the event, kept as written */
        OTHER
    }

    private record Line(Kind kind, JsonObject json, String raw)
    {
        static Line added(JsonObject recipeJson)
        {
            return new Line(Kind.ADDED, recipeJson, null);
        }

        static Line removed(JsonObject filter)
        {
            return new Line(Kind.REMOVED, filter, null);
        }

        String toScript()
        {
            return switch(kind)
            {
                case ADDED -> CUSTOM_PREFIX + compact(withoutIdAndName(json)) + ID_PREFIX + json.get("name").getAsString() + "')";
                case REMOVED -> REMOVE_PREFIX + compact(json) + ")";
                case REPLACED -> replacedScript(json);
                case OTHER -> raw;
            };
        }
    }

    /**
     * Read the lines of the recipes event. Recipes written by Craft Creator get back their "id" (the content hash, as
     * when they were created) and "name" (from the KubeJS recipe id).
     */
    private List<Line> readLines()
    {
        List<Line> lines = new ArrayList<>();
        Path scriptFile = getScriptFile();
        if(!Files.exists(scriptFile)) return lines;

        try
        {
            boolean inEvent = false;
            for(String fileLine : Files.readAllLines(scriptFile, StandardCharsets.UTF_8))
            {
                String trimmed = fileLine.trim();
                if(!inEvent)
                {
                    inEvent = trimmed.equals(EVENT_START);
                    continue;
                }
                if(trimmed.equals(EVENT_END)) break;
                if(trimmed.isEmpty()) continue;

                lines.add(parseLine(trimmed));
            }
        }
        catch(IOException e)
        {
            CraftCreatorAPI.LOGGER.error("Failed to read KubeJS script " + scriptFile, e);
        }
        return lines;
    }

    private static String replacedScript(JsonObject replacement)
    {
        boolean input = replacement.get("kind").getAsString().equals("input");
        return "event.replace" + (input ? "Input" : "Output") + "(" + compact(replacement.getAsJsonObject("filter")) + ", '"
                + replacement.get("from").getAsString() + "', " + (input ? "Ingredient" : "Item") + ".of('" + replacement.get("to").getAsString() + "'))";
    }

    private static Line parseLine(String line)
    {
        try
        {
            Matcher replaceMatcher = REPLACE_PATTERN.matcher(line);
            if(replaceMatcher.matches())
            {
                JsonObject replacement = new JsonObject();
                replacement.addProperty("kind", replaceMatcher.group(1).toLowerCase());
                replacement.add("filter", GsonProvider.compactGson().fromJson(replaceMatcher.group(2), JsonObject.class));
                replacement.addProperty("from", replaceMatcher.group(3));
                replacement.addProperty("to", replaceMatcher.group(4));
                return new Line(Kind.REPLACED, replacement, null);
            }

            int idStart = line.lastIndexOf(ID_PREFIX);
            if(line.startsWith(CUSTOM_PREFIX) && idStart > 0 && line.endsWith("')"))
            {
                JsonObject recipe = GsonProvider.compactGson().fromJson(line.substring(CUSTOM_PREFIX.length(), idStart), JsonObject.class);
                String name = line.substring(idStart + ID_PREFIX.length(), line.length() - 2);
                recipe.addProperty("id", RecipeSerializer.generateHash(recipe));
                recipe.addProperty("name", name);
                return Line.added(recipe);
            }

            if(line.startsWith(REMOVE_PREFIX) && line.endsWith(")"))
                return Line.removed(GsonProvider.compactGson().fromJson(line.substring(REMOVE_PREFIX.length(), line.length() - 1), JsonObject.class));
        }
        catch(Exception e)
        {
            CraftCreatorAPI.LOGGER.warn("Keeping unreadable line of the KubeJS script as is: " + line);
        }
        return new Line(Kind.OTHER, null, line);
    }

    /**
     * Rewrite the whole script from the lines.
     *
     * @return false if the file couldn't be written
     */
    private boolean writeLines(List<Line> lines)
    {
        StringBuilder script = new StringBuilder(HEADER).append('\n').append(EVENT_START).append('\n');
        lines.forEach(line -> script.append(INDENT).append(line.toScript()).append('\n'));
        script.append(EVENT_END).append('\n');

        Path scriptFile = getScriptFile();
        try
        {
            Files.createDirectories(scriptFile.getParent());
            Files.writeString(scriptFile, script.toString(), StandardCharsets.UTF_8);
            return true;
        }
        catch(IOException e)
        {
            CraftCreatorAPI.LOGGER.error("Failed to write KubeJS script " + scriptFile, e);
            return false;
        }
    }

    private static String compact(JsonObject json)
    {
        return GsonProvider.compactGson().toJson(json);
    }

    /**
     * The recipe json without Craft Creator's own "id" and "name" fields.
     */
    private static JsonObject withoutIdAndName(JsonObject recipeJson)
    {
        JsonObject copy = recipeJson.deepCopy();
        copy.remove("id");
        copy.remove("name");
        return copy;
    }
}
